import {
    addDoc,
    collection,
    deleteDoc,
    doc,
    getDoc,
    getDocs,
    orderBy,
    query,
    serverTimestamp,
    updateDoc,
} from "firebase/firestore";
import { db } from "./firebase";

// ── Types ─────────────────────────────────────────────────────────────────────

/** A single verse attached to a journal entry (the S in SOAP). */
export interface ScriptureRef {
  ref: string; // e.g. "John 3:16"
  text: string; // full verse text stored at save time
}

/** A complete SOAP journal entry as stored in Firestore and used in the UI. */
export interface JournalEntry {
  id: string;
  title: string | null;
  // ── SOAP fields ──────────────────────────────────────────────────────────
  scripture: ScriptureRef[]; // S — one or more attached verses
  observation: string; // O — what does the text say?
  application: string; // A — how does this apply to my life?
  prayer: string; // P — written prayer / response to God
  // ── Metadata ─────────────────────────────────────────────────────────────
  tags: string[]; // user-defined topic tags
  bookId: string | null; // e.g. "john" — for chapter-level filtering
  chapter: number | null; // e.g. 3
  createdAt: number; // Date.now()
  updatedAt: number; // Date.now() on every save
}

/**
 * Shape used when creating a new entry.
 * `id`, `createdAt`, and `updatedAt` are generated by the service.
 */
export type JournalEntryDraft = Omit<
  JournalEntry,
  "id" | "createdAt" | "updatedAt"
>;

/**
 * Shape used when editing an existing entry.
 * All fields are optional — only the provided ones are updated in Firestore.
 */
export type JournalEntryUpdate = Partial<JournalEntryDraft>;

// ── Firestore path ────────────────────────────────────────────────────────────

// Firestore path: users/{uid}/journal/{entryId}
function journalRef(uid: string) {
  return collection(db, "users", uid, "journal");
}

// ── CRUD ──────────────────────────────────────────────────────────────────────

/** Load all journal entries for a user, newest first. */
export async function loadEntries(uid: string): Promise<JournalEntry[]> {
  if (!uid) return [];
  const q = query(journalRef(uid), orderBy("createdAt", "desc"));
  const snapshot = await getDocs(q);
  return snapshot.docs.map((d) => {
    const data = d.data();
    return {
      id: d.id,
      title: (data.title as string | null) ?? null,
      scripture: (data.scripture as ScriptureRef[]) ?? [],
      observation: (data.observation as string) ?? "",
      application: (data.application as string) ?? "",
      prayer: (data.prayer as string) ?? "",
      tags: (data.tags as string[]) ?? [],
      bookId: (data.bookId as string | null) ?? null,
      chapter: (data.chapter as number | null) ?? null,
      createdAt: data.createdAt as number,
      updatedAt: data.updatedAt as number,
    };
  });
}

/** Create a new SOAP journal entry and return it with its Firestore-generated id. */
export async function addEntry(
  uid: string,
  draft: JournalEntryDraft,
): Promise<JournalEntry> {
  if (!uid) throw new Error("uid is required to add a journal entry");
  const now = Date.now();
  const ref = await addDoc(journalRef(uid), {
    ...draft,
    createdAt: now,
    updatedAt: now,
    createdAtServer: serverTimestamp(),
  });
  return { id: ref.id, ...draft, createdAt: now, updatedAt: now };
}

/** Update specific fields on an existing journal entry. */
export async function updateEntry(
  uid: string,
  entryId: string,
  changes: JournalEntryUpdate,
): Promise<void> {
  if (!uid) return;
  await updateDoc(doc(db, "users", uid, "journal", entryId), {
    ...changes,
    updatedAt: Date.now(),
  });
}

/** Load a single journal entry by its Firestore document ID. */
export async function loadEntry(
  uid: string,
  entryId: string,
): Promise<JournalEntry | null> {
  if (!uid || !entryId) return null;
  const snap = await getDoc(doc(db, "users", uid, "journal", entryId));
  if (!snap.exists()) return null;
  const data = snap.data();
  return {
    id: snap.id,
    title: (data.title as string | null) ?? null,
    scripture: (data.scripture as ScriptureRef[]) ?? [],
    observation: (data.observation as string) ?? "",
    application: (data.application as string) ?? "",
    prayer: (data.prayer as string) ?? "",
    tags: (data.tags as string[]) ?? [],
    bookId: (data.bookId as string | null) ?? null,
    chapter: (data.chapter as number | null) ?? null,
    createdAt: data.createdAt as number,
    updatedAt: data.updatedAt as number,
  };
}

/** Permanently delete a journal entry. */
export async function deleteEntry(uid: string, entryId: string): Promise<void> {
  if (!uid) return;
  await deleteDoc(doc(db, "users", uid, "journal", entryId));
}

// ── Stats ─────────────────────────────────────────────────────────────────────

const PHT = "Asia/Manila";

/** "YYYY-MM-DD" for a timestamp in Philippine Time. */
function getPHTDateStr(ts: number): string {
  return new Intl.DateTimeFormat("en-CA", { timeZone: PHT }).format(
    new Date(ts),
  );
}

/** Count consecutive days (ending today PHT) that have at least one entry. */
export function calcStreak(entries: JournalEntry[]): number {
  if (!entries.length) return 0;
  const unique = [...new Set(entries.map((e) => getPHTDateStr(e.createdAt)))]
    .sort()
    .reverse();
  const today = getPHTDateStr(Date.now());
  let streak = 0;
  let cursor = today;
  for (const date of unique) {
    if (date === cursor) {
      streak++;
      const d = new Date(cursor);
      d.setDate(d.getDate() - 1);
      cursor = getPHTDateStr(d.getTime());
    } else break;
  }
  return streak;
}
